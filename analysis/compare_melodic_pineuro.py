def get_fmriprep_rest_runs(fmriprep_dir: Path, subject: str) -> list[Path]:
    """Get fMRIPrep rest run paths (MNI space)."""
    func_dir = get_fmriprep_func_dir(fmriprep_dir, subject)
    pattern = "*_task-rest_run-*_space-MNI152NLin2009cAsym_desc-preproc_bold.nii.gz"
    return sorted(func_dir.glob(pattern))


def get_fmriprep_mask(fmriprep_dir: Path, subject: str) -> Path:
    """Get fMRIPrep brain mask (MNI space)."""
    func_dir = get_fmriprep_func_dir(fmriprep_dir, subject)
