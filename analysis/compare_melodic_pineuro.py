def cmd_status(args: argparse.Namespace) -> None:
    """Check status of all subjects."""
    if not args.output_dir.exists():
        print(f"Output directory not found: {args.output_dir}")
        return

    print("=" * 60)
    print("MELODIC COMPARISON STATUS")
    print("=" * 60)

    if args.csv:
        configs = load_subjects_csv(args.csv)
        subjects = [c.subject for c in configs]
    else:
        subjects = sorted([d.name for d in args.output_dir.iterdir() if d.is_dir()])

    for subject in subjects:
        melodic_dir = args.output_dir / subject / "melodic"

        parts = []
        if check_melodic_complete(melodic_dir):
            parts.append("melodic")
        if check_masks_complete(melodic_dir):
            parts.append("masks")
        if check_comparison_complete(melodic_dir):
            parts.append("compared")

        status = ", ".join(parts) if parts else "not started"
        print(f"  {subject}: {status}")


def print_summary(all_results: list[dict]) -> None:
    """Print final summary."""
    print("\n" + "=" * 60)
    print("FINAL SUMMARY")
    print("=" * 60)

    if not all_results:
        print("\nNo comparisons were completed.")
        return

    dice_by_network: dict[str, list[float]] = {}
    jaccard_by_network: dict[str, list[float]] = {}
    spatial_corr_by_network: dict[str, list[float]] = {}

    for r in all_results:
        print(f"\n{r['subject']}:")
        for network, metrics in r["results"].items():
            if network.startswith("_"):
                continue
            spatial_r = metrics.get("spatial_correlation")
            spatial_str = f", spatial_corr={spatial_r:.3f}" if spatial_r else ""
            print(f"  {network}: Dice={metrics['dice']:.4f}, Jaccard={metrics['jaccard']:.4f}{spatial_str}")

            if network not in dice_by_network:
                dice_by_network[network] = []
                jaccard_by_network[network] = []
                spatial_corr_by_network[network] = []

            dice_by_network[network].append(metrics["dice"])
            jaccard_by_network[network].append(metrics["jaccard"])
            if spatial_r is not None:
                spatial_corr_by_network[network].append(spatial_r)

    print("\n" + "-" * 60)
    print("STATISTICS BY NETWORK")
    print("-" * 60)

    for network in dice_by_network:
        dice_arr = np.array(dice_by_network[network])
        jaccard_arr = np.array(jaccard_by_network[network])

        print(f"\n{network} (n={len(dice_arr)}):")
        print(
            f"  Dice:    mean={dice_arr.mean():.4f}, std={dice_arr.std():.4f}, "
            f"min={dice_arr.min():.4f}, max={dice_arr.max():.4f}"
        )
        print(f"  Jaccard: mean={jaccard_arr.mean():.4f}, std={jaccard_arr.std():.4f}")

        if spatial_corr_by_network[network]:
            spatial_arr = np.array(spatial_corr_by_network[network])
            print(f"  Spatial corr: mean={spatial_arr.mean():.4f}, std={spatial_arr.std():.4f}")


