def main() -> None:
    parser = argparse.ArgumentParser(
        description="Compare MELODIC (fMRIPrep) and pineuro ICA masks",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    subparsers = parser.add_subparsers(dest="command", required=True)

    # Setup command
    setup_parser = subparsers.add_parser("setup", help="Run MELODIC + mask extraction")
    setup_parser.add_argument("--csv", type=Path, required=True, help="Path to subjects CSV")
    setup_parser.add_argument("--output-dir", type=Path, required=True, help="Output directory")
    setup_parser.add_argument("--fmriprep-dir", type=Path, required=True, help="fMRIPrep derivatives directory")
    setup_parser.add_argument("--n-components", type=int, default=30, help="Number of ICA components")
    setup_parser.add_argument("--threshold", type=int, default=2000, help="Voxels to keep in masks")
    setup_parser.add_argument("--targets", type=str, default="DefaultA,ContA", help="Target networks")
    setup_parser.add_argument("--smooth-fwhm", type=float, default=5.0, help="Smoothing FWHM in mm")
    setup_parser.add_argument("--highpass", type=float, default=0.01, help="Highpass filter cutoff in Hz")
    setup_parser.add_argument("--tr", type=float, default=1.2, help="TR in seconds")
    setup_parser.add_argument("--overwrite", action="store_true", help="Overwrite existing outputs")

    # Compare command
    compare_parser = subparsers.add_parser("compare", help="Compare MELODIC and pineuro masks")
    compare_parser.add_argument("--csv", type=Path, required=True, help="Path to subjects CSV")
    compare_parser.add_argument("--output-dir", type=Path, required=True, help="Output directory")
    compare_parser.add_argument("--fmriprep-dir", type=Path, required=True, help="fMRIPrep derivatives directory")
    compare_parser.add_argument("--targets", type=str, default="DefaultA,ContA", help="Target networks")
    compare_parser.add_argument("--overwrite", action="store_true", help="Overwrite existing outputs")

    # Status command
    status_parser = subparsers.add_parser("status", help="Check status")
    status_parser.add_argument("--csv", type=Path, help="Path to subjects CSV (optional)")
    status_parser.add_argument("--output-dir", type=Path, required=True, help="Output directory")

    args = parser.parse_args()

    if hasattr(args, "csv") and args.csv:
        args.csv = args.csv.resolve()
    if hasattr(args, "output_dir"):
        args.output_dir = args.output_dir.resolve()
    if hasattr(args, "fmriprep_dir") and args.fmriprep_dir:
        args.fmriprep_dir = args.fmriprep_dir.resolve()

    if args.command == "setup":
        cmd_setup(args)
    elif args.command == "compare":
        cmd_compare(args)
    elif args.command == "status":
        cmd_status(args)


if __name__ == "__main__":
    main()
