def run_compare_for_subject(
    subject: str,
    output_dir: Path,
    fmriprep_dir: Path,
    targets: list[str] | None = None,
    overwrite: bool = False,
) -> dict:
    """Run comparison for a single subject."""
    if targets is None:
        targets = ["DefaultA", "ContA"]
    subject_dir = get_subject_dir(output_dir, subject)
    melodic_dir = subject_dir / "melodic"

    print(f"\n{'#' * 60}")
    print(f"# MELODIC COMPARE: {subject}")
    print(f"{'#' * 60}")

    # Find MELODIC masks
    masks_dir = melodic_dir / "04_masks"
    melodic_masks = {}
    for target in targets:
        mask_path = masks_dir / f"{subject}_{target}_thr.nii.gz"
        if mask_path.exists():
            melodic_masks[target] = mask_path
        else:
            print(f"  Warning: MELODIC mask not found: {mask_path}")

    # Find pineuro masks
    pineuro_mask_dir = get_mask_extraction_dir(subject_dir) / "03_masks"
    pineuro_masks = {}
    for target in targets:
        thr_path = pineuro_mask_dir / f"{subject}_{target}_thr.nii.gz"
        cont_path = pineuro_mask_dir / f"{subject}_{target}.nii.gz"
        if thr_path.exists():
            pineuro_masks[target] = {
                "thresholded": thr_path,
                "continuous": cont_path if cont_path.exists() else None,
            }
        else:
            print(f"  Warning: pineuro mask not found: {thr_path}")

    # Load Yeo correlation CSVs
    melodic_corr_file = melodic_dir / "03_yeo_correlation" / "Yeo_IC_spatial_correlation.csv"
    pineuro_corr_file = pineuro_mask_dir / "Yeo_IC_spatial_correlation.csv"

    melodic_corr_df = pd.read_csv(melodic_corr_file) if melodic_corr_file.exists() else None
    pineuro_corr_df = pd.read_csv(pineuro_corr_file) if pineuro_corr_file.exists() else None

    melodic_yeo_corr = {}
    pineuro_yeo_corr = {}
    for target in targets:
        if melodic_corr_df is not None and target in melodic_corr_df.columns:
            melodic_yeo_corr[target] = melodic_corr_df[target].max()
        if pineuro_corr_df is not None and target in pineuro_corr_df.columns:
            pineuro_yeo_corr[target] = pineuro_corr_df[target].max()

    # Transform MELODIC masks to subject space
    print("\nTransforming MELODIC masks to subject space...")
    fmriprep_anat = get_fmriprep_anat_dir(fmriprep_dir, subject)
    fmriprep_func = get_fmriprep_func_dir(fmriprep_dir, subject)
    pineuro_boldref = get_preprocessing_dir(subject_dir) / f"{subject}_task-rest_boldref.nii.gz"

    comparison_dir = melodic_dir / "comparison"

    melodic_masks_subject = transform_melodic_masks_to_subject(
        melodic_masks,
        fmriprep_anat,
        fmriprep_func,
        pineuro_boldref,
        comparison_dir,
        overwrite=overwrite,
    )

    # Compare masks
    results = compare_masks(
        melodic_masks_subject,
        pineuro_masks,
        comparison_dir,
        melodic_yeo_corr=melodic_yeo_corr,
        pineuro_yeo_corr=pineuro_yeo_corr,
    )

    return results


