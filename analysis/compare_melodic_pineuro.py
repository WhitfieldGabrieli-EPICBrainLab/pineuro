def run_setup_for_subject(
    subject: str,
    output_dir: Path,
    fmriprep_dir: Path,
    n_components: int = 30,
    threshold: int = 2000,
    targets: list[str] | None = None,
    smooth_fwhm: float = 5.0,
    highpass: float = 0.01,
    tr: float = 1.2,
    overwrite: bool = False,
) -> dict[str, Path]:
    """Run MELODIC setup for a single subject."""
    if targets is None:
        targets = ["DefaultA", "ContA"]
    subject_dir = get_subject_dir(output_dir, subject)
    melodic_dir = subject_dir / "melodic"

    print(f"\n{'#' * 60}")
    print(f"# MELODIC SETUP: {subject}")
    print(f"{'#' * 60}")

    # Step 1: Concatenate rest runs
    print("\nStep 1: Concatenating rest runs...")
    rest_runs = get_fmriprep_rest_runs(fmriprep_dir, subject)
    if not rest_runs:
        raise FileNotFoundError(f"No rest runs found for {subject}")

    concat_file = melodic_dir / "01_input" / "rest_runs_concat.nii.gz"
    concatenate_rest_runs(rest_runs, concat_file, overwrite)

    # Step 2: Preprocess
    print("\nStep 2: Preprocessing (smoothing + highpass filtering)...")
    mask_file = get_fmriprep_mask(fmriprep_dir, subject)
    preproc_file = melodic_dir / "01_input" / "rest_runs_preproc.nii.gz"
    preprocess_for_ica(
        concat_file,
        mask_file,
        preproc_file,
        smooth_fwhm=smooth_fwhm,
        highpass=highpass,
        tr=tr,
        overwrite=overwrite,
    )

    # Step 3: Run MELODIC
    print("\nStep 3: Running MELODIC...")
    melodic_ic = run_melodic(
        preproc_file,
        mask_file,
        melodic_dir / "02_melodic",
        n_components,
        overwrite,
    )

    # Step 4: Compute Yeo correlation
    print("\nStep 4: Computing Yeo correlation...")
    corr_file = melodic_dir / "03_yeo_correlation" / "Yeo_IC_spatial_correlation.csv"
    corr_df = compute_yeo_correlation_mni(
        melodic_ic,
        mask_file,
        corr_file,
        n_yeo=17,
        overwrite=overwrite,
    )

    # Step 5: Extract network masks
    print("\nStep 5: Extracting network masks...")
    masks = extract_network_masks(
        melodic_ic,
        corr_df,
        melodic_dir / "04_masks",
        subject,
        targets,
        threshold,
        overwrite,
    )

    print(f"\nSetup complete for {subject}")
    return masks


