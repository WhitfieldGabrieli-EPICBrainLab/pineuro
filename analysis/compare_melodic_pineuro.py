#!/usr/bin/env python3
"""Compare MELODIC (fMRIPrep) and pineuro ICA masks.

Compares ICA-based network masks generated by:
1. FSL MELODIC on fMRIPrep-preprocessed rest data (in MNI space)
2. pineuro's CanICA on raw rest data (in subject space)

Both use spatial correlation with Yeo atlas to identify network components,
then threshold to retain top N voxels.

Requires:
- setup_validation.py to have been run first (pineuro preprocessing + mask extraction)
- fMRIPrep outputs at --fmriprep-dir

Usage:
    # Stage 1: Run MELODIC + mask extraction on fMRIPrep data
    python compare_melodic_pineuro.py setup \
        --csv analysis/remind_test_data.csv \
        --output-dir /data/output \
        --fmriprep-dir /projects/remind/derivatives/fmriprep/fmriprep-23.2.1

    # Stage 2: Compare masks
    python compare_melodic_pineuro.py compare \
        --csv analysis/remind_test_data.csv \
        --output-dir /data/output \
        --fmriprep-dir /projects/remind/derivatives/fmriprep/fmriprep-23.2.1

    # Check status
    python compare_melodic_pineuro.py status --output-dir /data/output
"""

