def compute_dice(mask1: np.ndarray, mask2: np.ndarray) -> float:
    """Compute Dice coefficient between two binary masks."""
    intersection = (mask1 & mask2).sum()
    return 2 * intersection / (mask1.sum() + mask2.sum())


def compute_jaccard(mask1: np.ndarray, mask2: np.ndarray) -> float:
    """Compute Jaccard index between two binary masks."""
    intersection = (mask1 & mask2).sum()
    union = (mask1 | mask2).sum()
    return intersection / union if union > 0 else 0.0


def compare_masks(
    melodic_masks: dict[str, dict],
    pineuro_masks: dict[str, dict],
    output_dir: Path,
    melodic_yeo_corr: dict[str, float] = None,
    pineuro_yeo_corr: dict[str, float] = None,
) -> dict:
    """Compare MELODIC and pineuro masks using Dice, Jaccard, and spatial correlation."""
    from scipy.stats import pearsonr

    output_dir.mkdir(parents=True, exist_ok=True)
    results = {}
    melodic_yeo_corr = melodic_yeo_corr or {}
    pineuro_yeo_corr = pineuro_yeo_corr or {}

    thresholds = [500, 1000, 1500, 2000]

    print("\n" + "=" * 60)
    print("COMPARISON RESULTS (subject space)")
    print("=" * 60)

    for network in melodic_masks:
        if network not in pineuro_masks:
            print(f"\n{network}: pineuro mask not found, skipping")
            continue

        melodic_thr = get_data(load_img(melodic_masks[network]["thresholded"])) > 0
        pineuro_thr = get_data(load_img(pineuro_masks[network]["thresholded"])) > 0

        dice = compute_dice(melodic_thr, pineuro_thr)
        jaccard = compute_jaccard(melodic_thr, pineuro_thr)

        melodic_r = melodic_yeo_corr.get(network)
        pineuro_r = pineuro_yeo_corr.get(network)

        results[network] = {
            "dice": dice,
            "jaccard": jaccard,
            "melodic_yeo_corr": melodic_r,
            "pineuro_yeo_corr": pineuro_r,
            "melodic_voxels": int(melodic_thr.sum()),
            "pineuro_voxels": int(pineuro_thr.sum()),
            "overlap_voxels": int((melodic_thr & pineuro_thr).sum()),
        }

        # Spatial correlation of continuous maps
        melodic_cont_path = melodic_masks[network].get("continuous")
        pineuro_cont_path = pineuro_masks[network].get("continuous")

        if (
            melodic_cont_path
            and pineuro_cont_path
            and Path(melodic_cont_path).exists()
            and Path(pineuro_cont_path).exists()
        ):
            melodic_cont = get_data(load_img(melodic_cont_path))
            pineuro_cont = get_data(load_img(pineuro_cont_path))

            brain_mask = (np.abs(melodic_cont) > 0.01) | (np.abs(pineuro_cont) > 0.01)

            if brain_mask.sum() > 100:
                spatial_corr, _ = pearsonr(melodic_cont[brain_mask], pineuro_cont[brain_mask])
                results[network]["spatial_correlation"] = spatial_corr

                # Tiered threshold analysis
                tiered_dice = {}
                for thr in thresholds:
                    mel_abs = np.abs(melodic_cont)
                    mel_flat = mel_abs.ravel()
                    mel_mask = np.zeros(mel_flat.shape, dtype=bool)
                    mel_mask[np.argpartition(mel_flat, -thr)[-thr:]] = True
                    mel_mask = mel_mask.reshape(melodic_cont.shape)

                    pin_abs = np.abs(pineuro_cont)
                    pin_flat = pin_abs.ravel()
                    pin_mask = np.zeros(pin_flat.shape, dtype=bool)
                    pin_mask[np.argpartition(pin_flat, -thr)[-thr:]] = True
                    pin_mask = pin_mask.reshape(pineuro_cont.shape)

                    tiered_dice[thr] = compute_dice(mel_mask, pin_mask)

                results[network]["tiered_dice"] = tiered_dice

        print(f"\n{network}:")
        print(f"  Dice coefficient: {dice:.4f}")
        print(f"  Jaccard index:    {jaccard:.4f}")
        if "spatial_correlation" in results[network]:
            print(f"  Spatial correlation: {results[network]['spatial_correlation']:.4f}")
        if "tiered_dice" in results[network]:
            print("  Tiered Dice: ", end="")
            print(", ".join(f"{k}={v:.4f}" for k, v in results[network]["tiered_dice"].items()))
        print(f"  MELODIC voxels:   {melodic_thr.sum()}")
        print(f"  pineuro voxels:   {pineuro_thr.sum()}")
        print(f"  Overlap voxels:   {(melodic_thr & pineuro_thr).sum()}")
        if melodic_r is not None:
            print(f"  MELODIC Yeo corr: {melodic_r:.4f}")
        if pineuro_r is not None:
            print(f"  pineuro Yeo corr: {pineuro_r:.4f}")

    # Cross-network comparisons (should be LOW - shows specificity)
    networks = list(melodic_masks.keys())
    cross_network_results = {}

    if len(networks) >= 2:
        print("\n" + "-" * 60)
        print("CROSS-NETWORK COMPARISONS (baseline - should be LOW)")
        print("-" * 60)

        cross_pairs = []
        for i, net1 in enumerate(networks):
            for net2 in networks[i + 1 :]:
                cross_pairs.append(("melodic", net1, "melodic", net2))
                cross_pairs.append(("pineuro", net1, "pineuro", net2))
                cross_pairs.append(("melodic", net1, "pineuro", net2))
                cross_pairs.append(("melodic", net2, "pineuro", net1))

        for method1, net1, method2, net2 in cross_pairs:
            pair_key = f"{method1}_{net1}_vs_{method2}_{net2}"

            mask1_dict = melodic_masks.get(net1) if method1 == "melodic" else pineuro_masks.get(net1)
            mask2_dict = melodic_masks.get(net2) if method2 == "melodic" else pineuro_masks.get(net2)

            if not mask1_dict or not mask2_dict:
                continue

            mask1_thr = get_data(load_img(mask1_dict["thresholded"])) > 0
            mask2_thr = get_data(load_img(mask2_dict["thresholded"])) > 0

            dice = compute_dice(mask1_thr, mask2_thr)
            jaccard = compute_jaccard(mask1_thr, mask2_thr)

            cross_network_results[pair_key] = {
                "dice": dice,
                "jaccard": jaccard,
                "method1": method1,
                "network1": net1,
                "method2": method2,
                "network2": net2,
            }

            cont1_path = mask1_dict.get("continuous")
            cont2_path = mask2_dict.get("continuous")

            if cont1_path and cont2_path and Path(cont1_path).exists() and Path(cont2_path).exists():
                cont1 = get_data(load_img(cont1_path))
                cont2 = get_data(load_img(cont2_path))

                brain_mask = (np.abs(cont1) > 0.01) | (np.abs(cont2) > 0.01)
                if brain_mask.sum() > 100:
                    spatial_corr, _ = pearsonr(cont1[brain_mask], cont2[brain_mask])
                    cross_network_results[pair_key]["spatial_correlation"] = spatial_corr

            spatial_str = ""
            if "spatial_correlation" in cross_network_results[pair_key]:
                spatial_str = f", spatial_corr={cross_network_results[pair_key]['spatial_correlation']:.4f}"
            print(f"  {method1} {net1} vs {method2} {net2}: Dice={dice:.4f}, Jaccard={jaccard:.4f}{spatial_str}")

    results["_cross_network"] = cross_network_results

    # Save report
    report_path = output_dir / "comparison_report.txt"
    with open(report_path, "w") as f:
        f.write("MELODIC vs pineuro Mask Comparison Report\n")
        f.write("=" * 60 + "\n\n")

        f.write("WITHIN-NETWORK COMPARISONS (MELODIC vs pineuro)\n")
        f.write("-" * 60 + "\n\n")
        for network, metrics in results.items():
            if network.startswith("_"):
                continue
            f.write(f"{network}:\n")
            for key, value in metrics.items():
                if value is None:
                    f.write(f"  {key}: N/A\n")
                elif isinstance(value, float):
                    f.write(f"  {key}: {value:.4f}\n")
                else:
                    f.write(f"  {key}: {value}\n")
            f.write("\n")

        if cross_network_results:
            f.write("\nCROSS-NETWORK COMPARISONS (baseline - should be LOW)\n")
            f.write("-" * 60 + "\n\n")
            for pair_key, metrics in cross_network_results.items():
                f.write(f"{metrics['method1']} {metrics['network1']} vs {metrics['method2']} {metrics['network2']}:\n")
                f.write(f"  dice: {metrics['dice']:.4f}\n")
                f.write(f"  jaccard: {metrics['jaccard']:.4f}\n")
                if "spatial_correlation" in metrics:
                    f.write(f"  spatial_correlation: {metrics['spatial_correlation']:.4f}\n")
                f.write("\n")

    print(f"\nReport saved: {report_path}")

    # Create comparison plot
    create_comparison_plot(melodic_masks, pineuro_masks, results, output_dir)

    return results


def create_comparison_plot(
    melodic_masks: dict[str, dict],
    pineuro_masks: dict[str, dict],
    results: dict,
    output_dir: Path,
) -> None:
    """Create visualization comparing masks (both in subject space)."""
    n_networks = len(melodic_masks)

    fig, axes = plt.subplots(n_networks, 3, figsize=(15, 5 * n_networks))
    if n_networks == 1:
        axes = axes.reshape(1, -1)

    for i, network in enumerate(melodic_masks.keys()):
        if network not in pineuro_masks:
            continue

        melodic_data = get_data(load_img(melodic_masks[network]["thresholded"])) > 0
        pineuro_data = get_data(load_img(pineuro_masks[network]["thresholded"])) > 0

        z_mid = melodic_data.shape[2] // 2

        axes[i, 0].imshow(melodic_data[:, :, z_mid].T, origin="lower", cmap="Blues")
        axes[i, 0].set_title(f"MELODIC {network}")
        axes[i, 0].axis("off")

        axes[i, 1].imshow(pineuro_data[:, :, z_mid].T, origin="lower", cmap="Oranges")
        axes[i, 1].set_title(f"pineuro {network}")
        axes[i, 1].axis("off")

        overlap = np.zeros((*melodic_data.shape[:2], 3))
        overlap[:, :, 2] = melodic_data[:, :, z_mid]
        overlap[:, :, 0] = pineuro_data[:, :, z_mid]
        overlap[:, :, 1] = melodic_data[:, :, z_mid] & pineuro_data[:, :, z_mid]

        axes[i, 2].imshow(np.transpose(overlap, (1, 0, 2)), origin="lower")
        metrics = results.get(network, {})
        axes[i, 2].set_title(f"Overlap (Dice={metrics.get('dice', 0):.3f})")
        axes[i, 2].axis("off")

    plt.tight_layout()
    plot_path = output_dir / "comparison_plot.png"
    plt.savefig(plot_path, dpi=150)
    plt.close()
    print(f"Plot saved: {plot_path}")


