def load_subjects_csv(csv_path: Path, output_dir: Path) -> list[SubjectConfig]:
    """Load subject configurations from CSV file.

    CSV format: subject,fmriprep_dir
    Or uses existing remind_test_data.csv and infers paths from output_dir.
    """
    configs = []

    with open(csv_path, "r", newline="", encoding="utf-8-sig") as f:
        import csv
        reader = csv.DictReader(f)

        for row in reader:
            subject = row["subject"].strip()
            if not subject:
                continue

            # Check if fmriprep_dir column exists
            if "fmriprep_dir" in row and row["fmriprep_dir"].strip():
                fmriprep_dir = Path(row["fmriprep_dir"].strip())
                # Infer pineuro_dir from fmriprep_dir (sibling directory)
                pineuro_dir = fmriprep_dir.parent
            else:
                # Infer from output_dir structure
                pineuro_dir = output_dir / subject
                fmriprep_dir = pineuro_dir / "fmriprep"

            configs.append(
                SubjectConfig(
                    subject=subject,
                    fmriprep_dir=fmriprep_dir,
                    pineuro_dir=pineuro_dir,
                )
            )

    return configs


