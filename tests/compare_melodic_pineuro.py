#!/usr/bin/env python3
"""Compare MELODIC (fMRIPrep) and pineuro ICA masks.

This script compares ICA-based network masks generated by:
1. FSL MELODIC on fMRIPrep-preprocessed rest data (in MNI space)
2. pineuro's CanICA on raw rest data (in subject space)

Both approaches use spatial correlation with Yeo atlas to identify network components,
then threshold to retain top N voxels. This script compares the resulting masks
using Dice and Jaccard overlap metrics.

Usage:
    # Stage 1: Run MELODIC + mask extraction
    python compare_melodic_pineuro.py setup \
        --csv tests/remind_test_data.csv \
        --output-dir /data/melodic_validation

    # Check status
    python compare_melodic_pineuro.py status --output-dir /data/melodic_validation

    # Stage 2: Compare masks
    python compare_melodic_pineuro.py compare \
        --csv tests/remind_test_data.csv \
        --output-dir /data/melodic_validation
"""

