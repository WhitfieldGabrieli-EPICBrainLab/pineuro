def concatenate_rest_runs(
    rest_runs: list[Path],
    output_file: Path,
    overwrite: bool = False,
) -> Path:
    """Concatenate multiple rest runs using fslmerge.

    Parameters
    ----------
    rest_runs : list of Path
        Paths to rest run NIfTI files
    output_file : Path
        Path to output concatenated file
    overwrite : bool
        Whether to overwrite existing output

    Returns
    -------
    Path
        Path to concatenated file
    """
    if output_file.exists() and not overwrite:
        print(f"  Concatenated file exists, skipping: {output_file.name}")
        return output_file

    output_file.parent.mkdir(parents=True, exist_ok=True)

    # Build fslmerge command
    cmd = ["fslmerge", "-t", str(output_file)] + [str(r) for r in rest_runs]

    print(f"  Concatenating {len(rest_runs)} rest runs...")
    result = subprocess.run(cmd, capture_output=True, text=True)

    if result.returncode != 0:
        raise RuntimeError(f"fslmerge failed: {result.stderr}")

    print(f"  Created: {output_file.name}")
    return output_file


def preprocess_for_ica(
    input_file: Path,
    mask_file: Path,
    output_file: Path,
    smooth_fwhm: float = 5.0,
    highpass: float = 0.01,
    tr: float = 1.2,
    overwrite: bool = False,
) -> Path:
    """Apply smoothing and highpass filtering before ICA.

    Matches pineuro's preprocessing for CanICA to ensure fair comparison.

    Parameters
    ----------
    input_file : Path
        Path to 4D input NIfTI file
    mask_file : Path
        Path to brain mask
    output_file : Path
        Path to output preprocessed file
    smooth_fwhm : float
        Smoothing FWHM in mm (default 5.0 to match pineuro)
    highpass : float
        Highpass filter cutoff in Hz (default 0.01 to match pineuro)
    tr : float
        TR in seconds (default 1.2)
    overwrite : bool
        Whether to overwrite existing output

    Returns
    -------
    Path
        Path to preprocessed file
    """
    if output_file.exists() and not overwrite:
        print(f"  Preprocessed file exists, skipping: {output_file.name}")
        return output_file

    output_file.parent.mkdir(parents=True, exist_ok=True)

    # Step 1: Smoothing
    # Convert FWHM to sigma: sigma = FWHM / (2 * sqrt(2 * ln(2))) ≈ FWHM / 2.355
    sigma = smooth_fwhm / 2.355

    smoothed_file = output_file.parent / "temp_smoothed.nii.gz"
    cmd_smooth = [
        "fslmaths", str(input_file),
        "-s", str(sigma),
        str(smoothed_file)
    ]

    print(f"  Applying {smooth_fwhm}mm FWHM smoothing...")
    result = subprocess.run(cmd_smooth, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"fslmaths smoothing failed: {result.stderr}")

    # Step 2: Highpass filtering
    # hp_sigma = 1 / (2 * TR * cutoff_freq) in volumes
    hp_sigma = 1.0 / (2.0 * tr * highpass)

    cmd_hp = [
        "fslmaths", str(smoothed_file),
        "-bptf", str(hp_sigma), "-1",  # -1 means no lowpass
        "-mas", str(mask_file),  # Apply mask
        str(output_file)
    ]

    print(f"  Applying {highpass}Hz highpass filter (sigma={hp_sigma:.1f} vols)...")
    result = subprocess.run(cmd_hp, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"fslmaths highpass failed: {result.stderr}")

    # Cleanup temp file
    if smoothed_file.exists():
        smoothed_file.unlink()

    print(f"  Created: {output_file.name}")
    return output_file


def run_melodic(
    input_file: Path,
    mask_file: Path,
    output_dir: Path,
    n_components: int = 30,
    overwrite: bool = False,
) -> Path:
    """Run FSL MELODIC ICA.

    Parameters
    ----------
    input_file : Path
        Path to 4D input NIfTI file
    mask_file : Path
        Path to brain mask
    output_dir : Path
        Path to output directory
    n_components : int
        Number of ICA components
    overwrite : bool
        Whether to overwrite existing output

    Returns
    -------
    Path
        Path to melodic_IC.nii.gz
    """
    melodic_ic = output_dir / "melodic_IC.nii.gz"

    if melodic_ic.exists() and not overwrite:
        print(f"  MELODIC output exists, skipping: {melodic_ic.name}")
        return melodic_ic

    output_dir.mkdir(parents=True, exist_ok=True)

    cmd = [
        "melodic",
        "-i", str(input_file),
        "-o", str(output_dir),
        "-m", str(mask_file),
        "-d", str(n_components),
        "--report",
        "--Oall",
    ]

    print(f"  Running MELODIC with {n_components} components...")
    result = subprocess.run(cmd, capture_output=True, text=True)

    if result.returncode != 0:
        raise RuntimeError(f"MELODIC failed: {result.stderr}")

    print(f"  Created: {melodic_ic.name}")
    return melodic_ic


def compute_yeo_correlation_mni(
    melodic_ic_file: Path,
    mask_file: Path,
    output_file: Path,
    n_yeo: int = 17,
    overwrite: bool = False,
) -> pd.DataFrame:
    """Compute spatial correlation between MELODIC components and Yeo atlas.

    Uses the same vectorized Pearson correlation approach as pineuro.

    Parameters
    ----------
    melodic_ic_file : Path
        Path to MELODIC IC file (4D)
    mask_file : Path
        Path to brain mask
    output_file : Path
        Path to save correlation CSV
    n_yeo : int
        Number of Yeo networks (7 or 17)
    overwrite : bool
        Whether to overwrite existing output

    Returns
    -------
    pd.DataFrame
        Correlation matrix (components x networks)
    """
    if output_file.exists() and not overwrite:
        print(f"  Correlation file exists, loading: {output_file.name}")
        return pd.read_csv(output_file)

    output_file.parent.mkdir(parents=True, exist_ok=True)

    # Load MELODIC components
    print("  Loading MELODIC components...")
    ic_img = load_img(melodic_ic_file)
    ic_data = get_data(ic_img)
    n_components = ic_data.shape[3]

    # Load brain mask
    mask_img = load_img(mask_file)
    mask_data = get_data(mask_img) > 0

    # Fetch and resample Yeo atlas
    print(f"  Fetching Yeo {n_yeo}-network atlas...")
    yeo_atlas = datasets.fetch_atlas_yeo_2011(n_networks=n_yeo, thickness="thick")
    yeo_img = load_img(yeo_atlas.maps)

    # Resample Yeo to match MELODIC resolution
    print("  Resampling Yeo atlas to MELODIC space...")
    yeo_resampled = resample_to_img(yeo_img, ic_img, interpolation='nearest')
    yeo_data = np.squeeze(get_data(yeo_resampled)).astype(int)

    # Get network labels
    labels = get_yeo_labels(n_yeo)

    # Flatten inside mask
    V = mask_data.sum()
    X = ic_data[mask_data].reshape(V, n_components)
    yeo_masked = yeo_data[mask_data]

    # Demean components
    X_dm = X - X.mean(axis=0, keepdims=True)
    x_norm = np.sqrt((X_dm**2).sum(axis=0))

    # Compute correlations (vectorized approach from pineuro)
    print("  Computing spatial correlations...")
    Y = np.stack([(yeo_masked == j + 1).astype(float) for j in range(len(labels))])
    Y_dm = Y - Y.mean(axis=1, keepdims=True)
    Y_norm = np.sqrt((Y_dm**2).sum(axis=1))

    # Matrix multiply: (n_components, V) @ (V, n_networks) = (n_components, n_networks)
    num = X_dm.T @ Y_dm.T
    correlation_matrix = num / (x_norm[:, None] * Y_norm[None, :])

    # Create DataFrame and save
    corr_df = pd.DataFrame(correlation_matrix, columns=labels)
    corr_df.to_csv(output_file, index=False)
    print(f"  Saved: {output_file.name}")

    return corr_df


def extract_network_masks(
    components_file: Path,
    corr_df: pd.DataFrame,
    output_dir: Path,
    participant_id: str,
    targets: list[str],
    threshold: int = 2000,
    overwrite: bool = False,
) -> dict[str, Path]:
    """Extract network masks from MELODIC components.

    Parameters
    ----------
    components_file : Path
        Path to MELODIC IC file
    corr_df : pd.DataFrame
        Correlation matrix from compute_yeo_correlation_mni
    output_dir : Path
        Path to output directory
    participant_id : str
        Participant ID for naming
    targets : list of str
        Target network names (e.g., ["DefaultA", "ContA"])
    threshold : int
        Number of voxels to keep
    overwrite : bool
        Whether to overwrite existing output

    Returns
    -------
    dict
        Mapping of network name to thresholded mask path
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    # Load components
    ic_img = load_img(components_file)
    ic_data = get_data(ic_img)

    masks = {}

    for target in targets:
        thr_file = output_dir / f"{participant_id}_{target}_thr.nii.gz"

        if thr_file.exists() and not overwrite:
            print(f"  Mask exists, skipping: {thr_file.name}")
            masks[target] = thr_file
            continue

        # Find component with max correlation for this network
        component_idx = int(corr_df[target].idxmax())
        correlation = corr_df[target].iloc[component_idx]
        print(f"  {target}: component {component_idx} (r={correlation:.3f})")

        # Extract component
        component_data = ic_data[..., component_idx]

        # Save unthresholded
        unthresholded_file = output_dir / f"{participant_id}_{target}.nii.gz"
        if not unthresholded_file.exists() or overwrite:
            unthresholded_img = nib.Nifti1Image(component_data, ic_img.affine, ic_img.header)
            nib.save(unthresholded_img, unthresholded_file)

        # Threshold to top N voxels
        flat = component_data.ravel()
        mask = np.zeros(flat.shape, dtype=bool)
        mask[np.argpartition(flat, -threshold)[-threshold:]] = True
        mask = mask.reshape(component_data.shape)
        thresholded = ((component_data * mask) > 0).astype(np.uint8)

        # Save thresholded mask
        thr_img = nib.Nifti1Image(thresholded, ic_img.affine, ic_img.header)
        nib.save(thr_img, thr_file)
        print(f"  Saved: {thr_file.name} ({thresholded.sum()} voxels)")

        masks[target] = thr_file

    return masks


def transform_melodic_masks_to_subject(
    melodic_masks: dict[str, Path],
    mnireg_dir: Path,
    subject_ref_file: Path,
    output_dir: Path,
    threshold: int = 2000,
    overwrite: bool = False,
) -> dict[str, Path]:
    """Transform MELODIC masks from MNI space to subject space.

    Transforms the unthresholded component map, then thresholds to ensure
    the same number of voxels as pineuro masks.

    Parameters
    ----------
    melodic_masks : dict
        Mapping of network name to THRESHOLDED mask path (in MNI space)
        Note: We derive unthresholded path by removing '_thr' suffix
    mnireg_dir : Path
        Path to pineuro's 02_mnireg directory containing transforms
    subject_ref_file : Path
        Path to subject space reference file (pineuro boldref)
    output_dir : Path
        Path to output directory
    threshold : int
        Number of voxels to keep after thresholding (default 2000)
    overwrite : bool
        Whether to overwrite existing output

    Returns
    -------
    dict
        Mapping of network name to transformed mask path
    """
    import ants

    output_dir.mkdir(parents=True, exist_ok=True)

    # Find inverse transform files (pineuro naming: *_inv_0.mat = affine, *_inv_1.nii.gz = warp)
    affine_files = list(mnireg_dir.glob("*_inv_0.mat"))
    warp_files = list(mnireg_dir.glob("*_inv_1.nii.gz"))

    if not affine_files or not warp_files:
        raise FileNotFoundError(f"Inverse transform files not found in {mnireg_dir}")

    # ANTs applies transforms in reverse order (last in list = applied first)
    # For MNI→subject: need inverse_warp first, then inverse_affine
    # So list should be [affine, warp] → ANTs applies warp first, then affine
    transform_list = [str(affine_files[0]), str(warp_files[0])]

    # Load subject space reference
    subject_ref = ants.image_read(str(subject_ref_file))

    transformed_masks = {}

    for network, thr_mask_path in melodic_masks.items():
        output_file = output_dir / f"melodic_{network}_subject.nii.gz"

        if output_file.exists() and not overwrite:
            print(f"  Transformed mask exists, skipping: {output_file.name}")
            transformed_masks[network] = output_file
            continue

        # Get unthresholded component path (remove _thr suffix)
        unthr_mask_path = thr_mask_path.parent / thr_mask_path.name.replace("_thr.nii.gz", ".nii.gz")
        if not unthr_mask_path.exists():
            print(f"  Warning: Unthresholded component not found: {unthr_mask_path}")
            print(f"  Falling back to thresholded mask")
            unthr_mask_path = thr_mask_path

        print(f"  Transforming {network} to subject space...")
        component_ants = ants.image_read(str(unthr_mask_path))

        # Apply inverse transforms (MNI → subject) with linear interpolation for continuous data
        transformed = ants.apply_transforms(
            fixed=subject_ref,
            moving=component_ants,
            transformlist=transform_list,
            interpolator='linear',
        )

        # Threshold to top N voxels in subject space (by absolute value)
        # ICA components can be positive or negative, so use abs for thresholding
        transformed_data = transformed.numpy()
        abs_data = np.abs(transformed_data)
        flat = abs_data.ravel()
        mask = np.zeros(flat.shape, dtype=bool)
        mask[np.argpartition(flat, -threshold)[-threshold:]] = True
        mask = mask.reshape(transformed_data.shape)
        thresholded = mask.astype(np.uint8)

        # Use ANTs to save with correct header
        transformed_ants = ants.from_numpy(
            thresholded,
            origin=transformed.origin,
            spacing=transformed.spacing,
            direction=transformed.direction,
        )
        ants.image_write(transformed_ants, str(output_file))
        print(f"  Saved: {output_file.name} ({thresholded.sum()} voxels)")

        transformed_masks[network] = output_file

    return transformed_masks


def compute_dice(mask1: np.ndarray, mask2: np.ndarray) -> float:
    """Compute Dice coefficient between two binary masks."""
    intersection = (mask1 & mask2).sum()
    return 2 * intersection / (mask1.sum() + mask2.sum())


def compute_jaccard(mask1: np.ndarray, mask2: np.ndarray) -> float:
    """Compute Jaccard index between two binary masks."""
    intersection = (mask1 & mask2).sum()
    union = (mask1 | mask2).sum()
    return intersection / union if union > 0 else 0.0


def compare_masks(
    melodic_masks: dict[str, Path],
    pineuro_masks: dict[str, Path],
    output_dir: Path,
    melodic_yeo_corr: dict[str, float] = None,
    pineuro_yeo_corr: dict[str, float] = None,
) -> dict:
    """Compare MELODIC and pineuro masks using Dice and Jaccard.

    Parameters
    ----------
    melodic_masks : dict
        Mapping of network name to MELODIC mask path (in subject space)
    pineuro_masks : dict
        Mapping of network name to pineuro mask path (in subject space)
    output_dir : Path
        Path to output directory
    melodic_yeo_corr : dict, optional
        Mapping of network name to MELODIC's Yeo correlation
    pineuro_yeo_corr : dict, optional
        Mapping of network name to pineuro's Yeo correlation

    Returns
    -------
    dict
        Comparison results for each network
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    results = {}
    melodic_yeo_corr = melodic_yeo_corr or {}
    pineuro_yeo_corr = pineuro_yeo_corr or {}

    print("\n" + "=" * 60)
    print("COMPARISON RESULTS (subject space)")
    print("=" * 60)

    for network in melodic_masks.keys():
        if network not in pineuro_masks:
            print(f"\n{network}: pineuro mask not found, skipping")
            continue

        # Load masks
        melodic_data = get_data(load_img(melodic_masks[network])) > 0
        pineuro_data = get_data(load_img(pineuro_masks[network])) > 0

        # Compute metrics
        dice = compute_dice(melodic_data, pineuro_data)
        jaccard = compute_jaccard(melodic_data, pineuro_data)

        # Get Yeo correlations
        melodic_r = melodic_yeo_corr.get(network)
        pineuro_r = pineuro_yeo_corr.get(network)

        results[network] = {
            "dice": dice,
            "jaccard": jaccard,
            "melodic_yeo_corr": melodic_r,
            "pineuro_yeo_corr": pineuro_r,
            "melodic_voxels": int(melodic_data.sum()),
            "pineuro_voxels": int(pineuro_data.sum()),
            "overlap_voxels": int((melodic_data & pineuro_data).sum()),
        }

        print(f"\n{network}:")
        print(f"  Dice coefficient: {dice:.4f}")
        print(f"  Jaccard index:    {jaccard:.4f}")
        print(f"  MELODIC voxels:   {melodic_data.sum()}")
        print(f"  pineuro voxels:   {pineuro_data.sum()}")
        print(f"  Overlap voxels:   {(melodic_data & pineuro_data).sum()}")
        if melodic_r is not None:
            print(f"  MELODIC Yeo corr: {melodic_r:.4f}")
        if pineuro_r is not None:
            print(f"  pineuro Yeo corr: {pineuro_r:.4f}")

    # Save report
    report_path = output_dir / "comparison_report.txt"
    with open(report_path, "w") as f:
        f.write("MELODIC vs pineuro Mask Comparison Report\n")
        f.write("=" * 60 + "\n\n")

        for network, metrics in results.items():
            f.write(f"{network}:\n")
            for key, value in metrics.items():
                if value is None:
                    f.write(f"  {key}: N/A\n")
                elif isinstance(value, float):
                    f.write(f"  {key}: {value:.4f}\n")
                else:
                    f.write(f"  {key}: {value}\n")
            f.write("\n")

    print(f"\nReport saved: {report_path}")

    # Create comparison plot
    create_comparison_plot(melodic_masks, pineuro_masks, results, output_dir)

    return results


def create_comparison_plot(
    melodic_masks: dict[str, Path],
    pineuro_masks: dict[str, Path],
    results: dict,
    output_dir: Path,
) -> None:
    """Create visualization comparing masks (both in subject space)."""
    n_networks = len(melodic_masks)

    fig, axes = plt.subplots(n_networks, 3, figsize=(15, 5 * n_networks))
    if n_networks == 1:
        axes = axes.reshape(1, -1)

    for i, network in enumerate(melodic_masks.keys()):
        if network not in pineuro_masks:
            continue

        # Load masks
        melodic_data = get_data(load_img(melodic_masks[network])) > 0
        pineuro_data = get_data(load_img(pineuro_masks[network])) > 0

        # Get middle slices
        z_mid = melodic_data.shape[2] // 2

        # MELODIC mask
        axes[i, 0].imshow(melodic_data[:, :, z_mid].T, origin='lower', cmap='Blues')
