@dataclass
class SubjectConfig:
    """Configuration for a single subject."""

    subject: str
    fmriprep_dir: Path  # Base fmriprep directory for subject
    pineuro_dir: Path   # Base pineuro analysis directory for subject

    @property
    def fmriprep_rest_runs(self) -> list[Path]:
        """Get fMRIPrep rest run paths (MNI space)."""
        func_dir = self.fmriprep_dir / "ses-loc" / "func"
        pattern = "*_task-rest_run-*_space-MNI152NLin2009cAsym_desc-preproc_bold.nii.gz"
        runs = sorted(func_dir.glob(pattern))
        return runs

    @property
    def fmriprep_mask(self) -> Path:
        """Get fMRIPrep brain mask (MNI space)."""
        func_dir = self.fmriprep_dir / "ses-loc" / "func"
        pattern = "*_task-rest_run-01_space-MNI152NLin2009cAsym_desc-brain_mask.nii.gz"
        masks = list(func_dir.glob(pattern))
        if not masks:
            raise FileNotFoundError(f"No brain mask found in {func_dir}")
        return masks[0]

    @property
    def pineuro_mask_dir(self) -> Path:
        """Get pineuro mask extraction directory."""
        return self.pineuro_dir / "mask_extraction" / "03_masks"

    @property
    def pineuro_mnireg_dir(self) -> Path:
        """Get pineuro MNI registration directory."""
        return self.pineuro_dir / "mask_extraction" / "02_mnireg"

    @property
    def pineuro_boldref(self) -> Path:
        """Get pineuro boldref file (subject space reference)."""
        preproc_dir = self.pineuro_dir / "preprocessing"
        pattern = f"{self.subject}_task-rest_boldref.nii.gz"
        boldref = preproc_dir / pattern
        if not boldref.exists():
            raise FileNotFoundError(f"Boldref not found: {boldref}")
        return boldref


