def check_masks_complete(melodic_dir: Path) -> bool:
    """Check if MELODIC masks have been extracted."""
    masks_dir = get_melodic_masks_dir(melodic_dir)
    masks = list(masks_dir.glob("*_thr.nii.gz"))
    return len(masks) >= 2


def check_comparison_complete(melodic_dir: Path) -> bool:
    """Check if comparison has been done."""
    report = get_comparison_dir(melodic_dir) / "comparison_report.txt"
    return report.exists()


